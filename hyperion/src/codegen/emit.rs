        buf.push_str("    assert_eq!(result, ProofTerm::PfRefl);\n");
        buf.push_str("}\n\n");

        buf.push_str("#[test]\nfn linearity_app_produces_proof_cong() {\n");
        buf.push_str("    // analyze_linearity(app(atom(f), atom(x)), T) should return\n");
