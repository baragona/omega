    // === TARTARUS: SMT Matching Loop Hang ===

    #[test]
    fn z3_timeout_on_quantifier_loop() {
        // This triggers a quantifier instantiation loop in Z3:
        // ∀x. f(x) = f(f(x)) with a query about a distant relation.
        // Without rlimit/timeout, Z3 spins forever.
        let input = "\
(set-logic UF)
(declare-sort S 0)
(declare-fun f (S) S)
(declare-fun g (S) S)
(declare-const a S)
(declare-const b S)
(assert (forall ((x S)) (= (f x) (f (f x)))))
(assert (forall ((x S)) (= (g (f x)) (f (g x)))))
(assert (not (= (g (g (g (g (g (f a)))))) (f (g (g (g (g (g a)))))))))
(check-sat)
";
        let result = run_z3(input);
        match result {
            SmtResult::Error(e) if e.contains("spawn") => {
                eprintln!("Z3 not available, skipping: {}", e);
                return;
            }
            SmtResult::Error(e) if e.contains("timeout") || e.contains("killed") => {
                // CORRECT: the IPC layer killed Z3 before it hung forever
            }
            SmtResult::Unknown => {
                // CORRECT: Z3 hit rlimit and returned unknown
            }
            SmtResult::Sat | SmtResult::Unsat => {
                // Z3 actually solved it — acceptable (solver got lucky)
            }
            SmtResult::Error(e) => {
                // Any other error is suspicious but not a hang
                eprintln!("Z3 returned error (not a hang): {}", e);
            }
        }
        // The key assertion: this test MUST complete in bounded time.
        // If run_z3 blocks forever, the test framework will kill us.
    }

